export function nearestColor(r: number, g: number, b: number, palette: RGB[]): RGB {
  let minDist = Infinity;
  let nearest = palette[0];
  for (const c of palette) {
    const d = (r - c[0]) ** 2 + (g - c[1]) ** 2 + (b - c[2]) ** 2;
    if (d < minDist) { minDist = d; nearest = c; }
  }
  return nearest;
}
